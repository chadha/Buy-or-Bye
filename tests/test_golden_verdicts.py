"""Golden regression set for the Decimal migration (BOB-URL-001 M2).

tests/fixtures/golden_verdicts.json was generated by scripts/make_golden_verdicts.py from the
float implementation (commit e3fda17) before money moved to Decimal. It is not regenerated.
Every case must produce exactly the same label, headline, reason texts, evidence values and
stats, compared as JSON, after applying only the documented corrections below.

Documented corrections (each must explain a real defect of float arithmetic):
* Kestrel Laptop 14 Pro: the 30-day median is exactly 1093.955 (middle prices 1093.44 and
  1094.47). Binary float holds it as 1093.95499..., so it rounded DOWN to 1093.95. Exact
  Decimal rounds half up to 1093.96. No label changes.
* The deal €1,093.95 against a claimed "was" €1,750.32: the claimed discount is exactly 37.5%
  ((1750.32 - 1093.95) / 1750.32 = 0.375). Float computed 0.37499999... and showed "-37%";
  exact Decimal shows "-38%" (half up). Applies only to that deal. No label changes.
"""

import copy
import json
import sys
from decimal import Decimal
from pathlib import Path
from statistics import median
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from make_golden_verdicts import run  # noqa: E402

GOLDEN = json.loads(
    (ROOT / "tests" / "fixtures" / "golden_verdicts.json").read_text(encoding="utf-8")
)
# Only the median / reference values are corrected; a deal price that happens to equal the old
# rounded median (the sweep's p=1.00 cases) must stay exactly as it was.
CORRECTIONS = [
    {
        "product": "Kestrel Laptop 14 Pro",
        "old": 1093.95,
        "new": 1093.96,
        "texts": [("(€1,093.95)", "(€1,093.96)"), ("days was €1,093.95,", "days was €1,093.96,")],
    },
]
# Exact-half percentages that float rounded down: (deal price, "was" price, old text, new text).
PERCENT_CORRECTIONS = [(1093.95, 1750.32, "Claimed −37%", "Claimed −38%")]
_MEDIAN_STATS = {"median_30", "reference_price"}
_MEDIAN_METRIC = "median daily lowest price"


def _fix_expected(expected: dict[str, Any], fix: dict[str, Any]) -> dict[str, Any]:
    out = copy.deepcopy(expected)
    for key in _MEDIAN_STATS:
        if out["stats"].get(key) == fix["old"]:
            out["stats"][key] = fix["new"]
    for reason in out["reasons"]:
        for old, new in fix["texts"]:
            reason["text"] = reason["text"].replace(old, new)
        for ev in reason["evidence"]:
            if ev["metric"].startswith(_MEDIAN_METRIC) and ev["value"] == fix["old"]:
                ev["value"] = fix["new"]
    return out


def corrected(case: dict[str, Any]) -> dict[str, Any]:
    expected = case["expected"]
    for fix in CORRECTIONS:
        if case["product"] == fix["product"]:
            expected = _fix_expected(expected, fix)
    deal = case["deal"]
    for price, was, old, new in PERCENT_CORRECTIONS:
        if deal["price"] == price and deal.get("was_price") == was:
            expected = copy.deepcopy(expected)
            for reason in expected["reasons"]:
                reason["text"] = reason["text"].replace(old, new)
    return expected


def test_golden_set_covers_every_label_and_reason():
    labels = {c["expected"]["label"] for c in GOLDEN}
    codes = {r["code"] for c in GOLDEN for r in c["expected"]["reasons"]}
    assert labels == {"BUY", "BYE", "WAIT", "NOT_ENOUGH_DATA"}
    assert len(codes) == 9


def test_corrections_never_change_a_label_or_reason_code():
    for case in GOLDEN:
        before, after = case["expected"], corrected(case)
        assert before["label"] == after["label"]
        assert [r["code"] for r in before["reasons"]] == [r["code"] for r in after["reasons"]]


def test_kestrel_correction_is_a_real_half_cent():
    data = json.loads((ROOT / "app" / "demo_data.json").read_text(encoding="utf-8"))["products"]
    kestrel = next(p for p in data if p["name"] == "Kestrel Laptop 14 Pro")
    exact = median(Decimal(repr(h["price"])) for h in kestrel["history"][-30:])
    assert exact == Decimal("1093.955")
    assert round(1093.955, 2) == 1093.95  # the float defect the correction removes


def test_percent_correction_is_an_exact_half():
    for price, was, _, _ in PERCENT_CORRECTIONS:
        claimed = (Decimal(repr(was)) - Decimal(repr(price))) / Decimal(repr(was)) * 100
        assert claimed == Decimal("37.5")
        assert f"{(was - price) / was * 100:.0f}" == "37"  # the float defect


def test_every_correction_is_still_needed():
    for fix in CORRECTIONS:
        hits = [
            c for c in GOLDEN if c["product"] == fix["product"] and corrected(c) != c["expected"]
        ]
        assert hits, f"correction for {fix['product']} no longer applies: remove it"
    for price, was, _, _ in PERCENT_CORRECTIONS:
        assert any(
            c["deal"]["price"] == price and c["deal"].get("was_price") == was for c in GOLDEN
        )


@pytest.mark.parametrize("case", GOLDEN, ids=[c["id"] for c in GOLDEN])
def test_verdict_matches_golden(case):
    assert run(case) == corrected(case)
